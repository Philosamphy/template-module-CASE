-- 005_audit_events.sql — append-only, hash-chained audit trail.
--
-- Every privileged action (template lifecycle, workflow execution, membership)
-- appends one row. Each row stores the SHA-256 digest of its own canonical
-- payload plus the previous row's hash, so editing or deleting any row breaks
-- the chain from that point on. Verification re-computes the whole chain.
--
-- event_seq is BY DEFAULT (not ALWAYS) so the writer can allocate the next
-- value under an advisory lock and hash it before inserting.

CREATE TABLE IF NOT EXISTS audit_events (
  audit_id      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  event_seq     BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
  recorded_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  actor_id      TEXT NOT NULL,
  actor_role    TEXT NOT NULL CHECK (actor_role IN ('admin', 'operator', 'auditor', 'system')),
  action        TEXT NOT NULL CHECK (action <> ''),
  target_type   TEXT NOT NULL DEFAULT '',
  target_id     TEXT NOT NULL DEFAULT '',
  outcome       TEXT NOT NULL CHECK (outcome IN ('SUCCESS', 'FAILURE', 'PENDING')),
  details       JSONB NOT NULL DEFAULT '{}'::jsonb,
  prev_hash     TEXT NOT NULL,
  hash          TEXT NOT NULL CHECK (hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX IF NOT EXISTS idx_audit_events_recorded ON audit_events (recorded_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_events_action ON audit_events (action);
CREATE INDEX IF NOT EXISTS idx_audit_events_actor ON audit_events (actor_id);
